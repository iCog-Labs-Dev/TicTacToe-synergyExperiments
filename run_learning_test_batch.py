#!/usr/bin/env python3

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path


DEFAULT_LAUNCHER = Path("../../petta/PeTTa-alt/run.sh")
DEFAULT_METTA_FILE = Path("learning-test.metta")
DEFAULT_BELIEF_FILE = Path("WM/belief.metta")
DEFAULT_PERCEPTION_FILE = Path("WM/perception.metta")
DEFAULT_STATE_FILE = Path("WM/state.metta")
DEFAULT_LOG_ROOT = Path("run_logs")

PERCENT_RE = re.compile(
    r"\(([0-9]+(?:\.[0-9]+)?) percent of the moves made were generated by pln\)"
)
TOTAL_MOVES_RE = re.compile(r"\(NumberOfMovesMade: ([0-9]+(?:\.[0-9]+)?)\)")
PLN_MOVES_RE = re.compile(
    r"\(PLNMoves: ([0-9]+(?:\.[0-9]+)?) WinMoves: ([0-9]+(?:\.[0-9]+)?) CommonMoves: ([0-9]+(?:\.[0-9]+)?)\)"
)


@dataclass
class RunResult:
    run_name: str
    pln_percent: float
    total_moves: float
    pln_moves: float
    win_moves: float
    common_moves: float
    log_path: Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run petta-alt on a MeTTa file multiple times, resetting belief, "
            "perception, and state before each run."
        )
    )
    parser.add_argument(
        "runs",
        type=int,
        help="Number of clean runs to execute.",
    )
    parser.add_argument(
        "--launcher",
        type=Path,
        default=DEFAULT_LAUNCHER,
        help=f"Path to the petta launcher. Default: {DEFAULT_LAUNCHER}",
    )
    parser.add_argument(
        "--metta-file",
        type=Path,
        default=DEFAULT_METTA_FILE,
        help=f"MeTTa file to run. Default: {DEFAULT_METTA_FILE}",
    )
    parser.add_argument(
        "--belief-file",
        type=Path,
        default=DEFAULT_BELIEF_FILE,
        help=f"Belief file to clear before each run. Default: {DEFAULT_BELIEF_FILE}",
    )
    parser.add_argument(
        "--perception-file",
        type=Path,
        default=DEFAULT_PERCEPTION_FILE,
        help=(
            f"Perception file to clear before each run. "
            f"Default: {DEFAULT_PERCEPTION_FILE}"
        ),
    )
    parser.add_argument(
        "--state-file",
        type=Path,
        default=DEFAULT_STATE_FILE,
        help=f"State file to reset before each run. Default: {DEFAULT_STATE_FILE}",
    )
    parser.add_argument(
        "--log-root",
        type=Path,
        default=DEFAULT_LOG_ROOT,
        help=f"Directory under which run logs are created. Default: {DEFAULT_LOG_ROOT}",
    )
    return parser.parse_args()


def reset_files(belief_file: Path, perception_file: Path, state_file: Path) -> None:
    belief_file.write_text("", encoding="utf-8")
    perception_file.write_text("", encoding="utf-8")
    state_file.write_text("(Count 0)\n(GameCount 0)\n", encoding="utf-8")


def parse_log(log_path: Path) -> RunResult:
    text = log_path.read_text(encoding="utf-8", errors="replace")

    percent_match = PERCENT_RE.findall(text)
    total_moves_match = TOTAL_MOVES_RE.findall(text)
    pln_moves_match = PLN_MOVES_RE.findall(text)

    if not percent_match:
        raise RuntimeError(f"Could not parse PLN percentage from {log_path}")
    if not total_moves_match:
        raise RuntimeError(f"Could not parse total move count from {log_path}")
    if not pln_moves_match:
        raise RuntimeError(f"Could not parse PLN move counts from {log_path}")

    pln_moves, win_moves, common_moves = map(float, pln_moves_match[-1])
    return RunResult(
        run_name=log_path.name,
        pln_percent=float(percent_match[-1]),
        total_moves=float(total_moves_match[-1]),
        pln_moves=pln_moves,
        win_moves=win_moves,
        common_moves=common_moves,
        log_path=log_path,
    )


def write_summary(log_dir: Path, results: list[RunResult]) -> Path:
    summary_path = log_dir / "summary.tsv"
    avg_percent = sum(r.pln_percent for r in results) / len(results)
    total_moves = sum(r.total_moves for r in results)
    total_pln_moves = sum(r.pln_moves for r in results)
    weighted_percent = (total_pln_moves / total_moves * 100.0) if total_moves else 0.0

    with summary_path.open("w", encoding="utf-8") as handle:
        handle.write(
            "run\tpln_percent\ttotal_moves\tpln_moves\twin_moves\tcommon_moves\tlog_path\n"
        )
        for result in results:
            handle.write(
                f"{result.run_name}\t{result.pln_percent}\t{result.total_moves}\t"
                f"{result.pln_moves}\t{result.win_moves}\t{result.common_moves}\t"
                f"{result.log_path}\n"
            )
        handle.write(
            f"FINAL_SUMMARY\t{avg_percent}\t{weighted_percent}\t{total_moves}\t"
            f"{total_pln_moves}\t{len(results)}\t{summary_path}\n"
        )
    return summary_path


def main() -> int:
    args = parse_args()

    if args.runs <= 0:
        print("runs must be greater than 0", file=sys.stderr)
        return 2

    launcher = args.launcher.resolve()
    metta_file = args.metta_file.resolve()
    belief_file = args.belief_file.resolve()
    perception_file = args.perception_file.resolve()
    state_file = args.state_file.resolve()
    log_root = args.log_root.resolve()

    if not launcher.exists():
        print(f"Launcher not found: {launcher}", file=sys.stderr)
        return 2
    if not metta_file.exists():
        print(f"MeTTa file not found: {metta_file}", file=sys.stderr)
        return 2

    log_root.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    log_dir = log_root / f"petta_alt_{timestamp}"
    log_dir.mkdir(parents=True, exist_ok=True)

    results: list[RunResult] = []

    for run_idx in range(1, args.runs + 1):
        reset_files(belief_file, perception_file, state_file)

        log_path = log_dir / f"run_{run_idx}.log"
        with log_path.open("w", encoding="utf-8") as handle:
            completed = subprocess.run(
                [str(launcher), str(metta_file), "-s"],
                stdout=handle,
                stderr=subprocess.STDOUT,
                check=False,
                cwd=metta_file.parent,
            )

        if completed.returncode != 0:
            print(
                f"Run {run_idx} failed with exit code {completed.returncode}: {log_path}",
                file=sys.stderr,
            )
            return completed.returncode

        result = parse_log(log_path)
        results.append(result)
        print(f"completed_run={run_idx} log={log_path}")

    summary_path = write_summary(log_dir, results)
    avg_percent = sum(r.pln_percent for r in results) / len(results)
    total_moves = sum(r.total_moves for r in results)
    total_pln_moves = sum(r.pln_moves for r in results)
    weighted_percent = (total_pln_moves / total_moves * 100.0) if total_moves else 0.0

    print(f"LOGDIR\t{log_dir}")
    for result in results:
        print(
            f"{result.run_name}\t{result.pln_percent}\t{result.total_moves}\t"
            f"{result.pln_moves}\t{result.win_moves}\t{result.common_moves}"
        )
    print(
        "FINAL_SUMMARY\t"
        f"runs={len(results)}\t"
        f"avg_percent={avg_percent}\t"
        f"weighted_percent={weighted_percent}\t"
        f"total_moves={total_moves}\t"
        f"total_pln_moves={total_pln_moves}\t"
        f"summary={summary_path}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
